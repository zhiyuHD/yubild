//! CMake 后端。
//!
//! 这一层是纯函数：给定模型和 target 顺序，产出一份完整的 `CMakeLists.txt`。
//! 不落盘、不调外部进程，便于单测。
//!
//! 两条硬规则：
//! 1. 交叉编译的编译器/系统名必须在 `project()` 之前设置，否则 CMake 已经按宿主平台探测完毕。
//! 2. 输出必须幂等 —— 同样的输入永远得到同样的字节，否则构建目录会被无谓地重新配置。

use std::collections::HashMap;
use std::fmt::Write as _;

use crate::model::{Config, DepKind, PostBuildStep, Target};

/// 生成文件声明的最低 CMake 版本。CMake 4.x 不再兼容 < 3.5 的写法，这里留足余量。
pub const MIN_CMAKE_VERSION: &str = "3.20";

/// 生成所需的外部上下文（测试库位置、自动生成的 main 文件）。
#[derive(Default)]
pub struct EmitOptions<'a> {
    /// 测试库头文件目录（绝对路径）。
    pub testkit_dir: Option<&'a str>,
    /// 测试 target 名 -> 自动生成的 main 源文件绝对路径。
    pub test_main: Option<&'a HashMap<String, String>>,
}

pub fn emit(cfg: &Config, order: &[usize], opts: &EmitOptions) -> String {
    let mut s = String::with_capacity(4096);
    let root = normalize_root(cfg.source_root.as_deref().unwrap_or("."));

    let _ = writeln!(
        s,
        "# Generated by yubild {} -- DO NOT EDIT.",
        env!("CARGO_PKG_VERSION")
    );
    let _ = writeln!(
        s,
        "# Config: {}",
        cfg.config_file.as_deref().unwrap_or("yubild.py")
    );
    let _ = writeln!(s, "# 改动请编辑 yubild.py 后重新执行: yubild generate");
    let _ = writeln!(s);
    let _ = writeln!(s, "cmake_minimum_required(VERSION {MIN_CMAKE_VERSION})");

    emit_toolchain(&mut s, cfg);
    emit_cmake_snippets(
        &mut s,
        "project() 之前的 CMake 片段",
        &cfg.cmake.before_project,
    );
    emit_project(&mut s, cfg, &root);
    emit_cmake_snippets(
        &mut s,
        "project() 之后的 CMake 片段",
        &cfg.cmake.after_project,
    );
    emit_dependencies(&mut s, cfg);
    emit_targets(&mut s, cfg, order, opts);

    s
}

fn emit_toolchain(s: &mut String, cfg: &Config) {
    let tc = &cfg.toolchain;
    if !tc.is_cross() {
        return;
    }
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "# --- 交叉编译工具链（由 toolchain() 生成，必须位于 project() 之前） ---"
    );
    if let Some(sys) = &tc.system_name {
        let _ = writeln!(s, "set(CMAKE_SYSTEM_NAME {sys})");
    }
    if let Some(cc) = tc.resolved_c() {
        let _ = writeln!(s, "set(CMAKE_C_COMPILER {})", quote(&cc));
    }
    if let Some(cxx) = tc.resolved_cxx() {
        let _ = writeln!(s, "set(CMAKE_CXX_COMPILER {})", quote(&cxx));
    }
    let _ = writeln!(s, "set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)");
    let _ = writeln!(s, "set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)");
    let _ = writeln!(s, "set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)");
}

fn emit_project(s: &mut String, cfg: &Config, root: &str) {
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "project({} VERSION {} LANGUAGES C CXX)",
        cfg.project.name, cfg.project.version
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "set(CMAKE_CXX_STANDARD {})", cfg.project.cxx_std);
    let _ = writeln!(s, "set(CMAKE_CXX_STANDARD_REQUIRED ON)");
    let _ = writeln!(s, "set(CMAKE_CXX_EXTENSIONS OFF)");
    let _ = writeln!(s, "set(CMAKE_POSITION_INDEPENDENT_CODE ON)");
    let _ = writeln!(s, "set(CMAKE_EXPORT_COMPILE_COMMANDS ON)");
    let _ = writeln!(s, "set(YUBILD_SOURCE_ROOT {})", quote_always(root));
    let _ = writeln!(s);

    s.push_str("if(NOT CMAKE_BUILD_TYPE AND NOT CMAKE_CONFIGURATION_TYPES)\n");
    s.push_str("  set(CMAKE_BUILD_TYPE Debug CACHE STRING \"Build type\" FORCE)\n");
    s.push_str("endif()\n\n");
    s.push_str("set(CMAKE_RUNTIME_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/bin)\n");
    s.push_str("set(CMAKE_LIBRARY_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/lib)\n");
    s.push_str("set(CMAKE_ARCHIVE_OUTPUT_DIRECTORY ${CMAKE_BINARY_DIR}/lib)\n");

    if cfg.toolchain.static_runtime == Some(true) {
        let _ = writeln!(s);
        s.push_str("if(MSVC)\n");
        s.push_str("  set(CMAKE_MSVC_RUNTIME_LIBRARY \"MultiThreaded$<$<CONFIG:Debug>:Debug>\")\n");
        s.push_str("endif()\n");
    }
}

fn emit_cmake_snippets(s: &mut String, title: &str, snippets: &[String]) {
    if snippets.is_empty() {
        return;
    }
    let _ = writeln!(s);
    let _ = writeln!(s, "# --- {title}（由 cmake() 注入，原样输出） ---");
    for code in snippets {
        let _ = writeln!(s, "{code}");
    }
}

/// 把 `@exe_dir` 这类占位符展开成 CMake 表达式。
///
/// 用 `$<TARGET_FILE_DIR:t>` 而不是固定路径，是为了在多配置生成器（Ninja Multi-Config、
/// MSVC）下也能落到「当前配置」的输出目录，而不是永远 Debug。
fn expand_placeholders(value: &str, target: &str) -> String {
    value
        .replace("@exe_dir", &format!("$<TARGET_FILE_DIR:{target}>"))
        .replace("@build_dir", "${CMAKE_BINARY_DIR}")
        .replace("@source_dir", "${YUBILD_SOURCE_ROOT}")
}

/// 源路径语义：相对路径相对项目根，绝对路径和 `${...}` 表达式原样保留。
///
/// 必须是绝对路径，否则 CMake 会以构建目录为基准解析，拷不到文件。
fn resolve_src(value: &str, target: &str) -> String {
    let expanded = expand_placeholders(value, target);
    if expanded.starts_with('$') || is_absolute(&expanded) {
        quote_always(&expanded)
    } else {
        format!("\"${{YUBILD_SOURCE_ROOT}}/{}\"", to_posix(&expanded))
    }
}

/// 目标目录语义：相对路径相对可执行文件目录（即 `@exe_dir`）。
fn resolve_dest_raw(value: &str, target: &str) -> String {
    let expanded = expand_placeholders(value, target);
    if expanded.starts_with('$') || is_absolute(&expanded) {
        expanded
    } else {
        format!("$<TARGET_FILE_DIR:{target}>/{}", to_posix(&expanded))
    }
}

fn resolve_dest(value: &str, target: &str) -> String {
    quote_always(&resolve_dest_raw(value, target))
}

/// `cmake -E copy_directory` 拷的是「目录内容」，语义上容易把 `assets/` 摊平到 bin 里。
/// 这里显式保留目录名：`copy_dir("data/assets", dest="@exe_dir")` -> `bin/assets/...`
fn dir_basename(path: &str) -> String {
    let trimmed = path.trim_end_matches(['/', '\\']);
    match trimmed.rsplit(['/', '\\']).next() {
        Some(last) if !last.is_empty() => last.to_string(),
        _ => trimmed.to_string(),
    }
}

fn emit_post_build(s: &mut String, t: &Target) {
    if t.post_build.is_empty() {
        return;
    }
    let _ = writeln!(s);
    let _ = writeln!(s, "# --- {} 的 POST_BUILD ---", t.name);
    let _ = writeln!(s, "add_custom_command(TARGET {} POST_BUILD", t.name);

    for step in &t.post_build {
        match step {
            PostBuildStep::Command { program, args } => {
                let _ = write!(
                    s,
                    "  COMMAND {}",
                    quote_always(&expand_placeholders(program, &t.name))
                );
                for a in args {
                    let _ = write!(s, " {}", quote_always(&expand_placeholders(a, &t.name)));
                }
                s.push('\n');
            }
            PostBuildStep::Copy { sources, dest } => {
                let dest_expr = resolve_dest(dest, &t.name);
                for src in sources {
                    s.push_str("  COMMAND ${CMAKE_COMMAND} -E copy_if_different\n");
                    let _ = writeln!(s, "          {} {}", resolve_src(src, &t.name), dest_expr);
                }
            }
            PostBuildStep::CopyDir { src, dest } => {
                let parent = resolve_dest_raw(dest, &t.name);
                let dest_dir = format!("{}/{}", parent.trim_end_matches('/'), dir_basename(src));
                s.push_str("  COMMAND ${CMAKE_COMMAND} -E copy_directory\n");
                let _ = writeln!(
                    s,
                    "          {} {}",
                    resolve_src(src, &t.name),
                    quote_always(&dest_dir)
                );
            }
            PostBuildStep::Symlink { src, dest, name } => {
                // 可重复执行：先删旧链接再建，避免「文件已存在」导致构建失败
                let parent = resolve_dest_raw(dest, &t.name);
                let link_name = name.clone().unwrap_or_else(|| dir_basename(src));
                let link = format!("{}/{}", parent.trim_end_matches('/'), link_name);
                let _ = writeln!(
                    s,
                    "  COMMAND ${{CMAKE_COMMAND}} -E rm -f {}",
                    quote_always(&link)
                );
                let _ = writeln!(
                    s,
                    "  COMMAND ${{CMAKE_COMMAND}} -E create_symlink {} {}",
                    resolve_src(src, &t.name),
                    quote_always(&link)
                );
            }
        }
    }

    let _ = writeln!(s, "  COMMENT \"yubild: {} 的 POST_BUILD\"", t.name);
    s.push_str("  VERBATIM\n");
    s.push_str(")\n");
}

fn emit_dependencies(s: &mut String, cfg: &Config) {
    if cfg.dependencies.is_empty() {
        return;
    }
    let _ = writeln!(s);
    let _ = writeln!(s, "# --- 外部依赖 ---");

    let mut pkg_config_emitted = false;
    for d in &cfg.dependencies {
        match d.kind {
            DepKind::FindPackage => {
                let pkg = d.package_name();
                let mut line = format!("find_package({pkg}");
                if let Some(v) = &d.version {
                    let _ = write!(line, " {v}");
                }
                if d.required {
                    let _ = write!(line, " REQUIRED");
                } else {
                    let _ = write!(line, " QUIET");
                }
                let _ = writeln!(line, ")");
                let _ = writeln!(s, "{}", line.trim_end());
            }
            DepKind::PkgConfig => {
                if !pkg_config_emitted {
                    let _ = writeln!(s, "find_package(PkgConfig REQUIRED)");
                    pkg_config_emitted = true;
                }
                let pkg = d.package_name();
                let var = pkg_config_var(pkg);
                let _ = writeln!(s, "pkg_check_modules({var} REQUIRED IMPORTED_TARGET {pkg})");
            }
            DepKind::Git => {
                let _ = writeln!(s, "include(FetchContent)");
                let repo = d.url.as_deref().unwrap_or("");
                let tag = d.tag.as_deref().unwrap_or("main");
                let id = sanitize_ident(&d.name);
                let _ = writeln!(
                    s,
                    "FetchContent_Declare({id} GIT_REPOSITORY {} GIT_TAG {tag})",
                    quote(repo)
                );
                let _ = writeln!(s, "FetchContent_MakeAvailable({id})");
            }
            DepKind::Subdir => {
                let rel = d.subdir.as_deref().unwrap_or(&d.name);
                let _ = writeln!(
                    s,
                    "add_subdirectory({} ${{CMAKE_BINARY_DIR}}/_deps/{} )",
                    src_path(rel),
                    sanitize_ident(&d.name)
                );
            }
        }
    }
}

fn emit_targets(s: &mut String, cfg: &Config, order: &[usize], opts: &EmitOptions) {
    if cfg.targets.is_empty() {
        return;
    }
    for &i in order {
        let t = &cfg.targets[i];
        let _ = writeln!(s);
        let _ = writeln!(s, "# --- target: {} ({}) ---", t.name, t.kind);

        let mut sources: Vec<String> = t.sources.iter().map(|p| src_path(p)).collect();
        if t.test {
            // 新增源文件必须参与构建，顺序无所谓，但放最前面便于阅读生成结果
            if let Some(main) = opts.test_main.and_then(|m| m.get(&t.name)) {
                sources.insert(0, quote_always(&to_posix(main)));
            }
        }
        match t.kind.cmake_type() {
            Some(kind) => {
                let _ = writeln!(s, "add_library({} {} {})", t.name, kind, sources.join(" "));
            }
            None => {
                let _ = writeln!(s, "add_executable({} {})", t.name, sources.join(" "));
            }
        }

        if !t.public_includes.is_empty() {
            let dirs: Vec<String> = t.public_includes.iter().map(|p| inc_path(p)).collect();
            let _ = writeln!(
                s,
                "target_include_directories({} PUBLIC {})",
                t.name,
                dirs.join(" ")
            );
        }
        if !t.include_dirs.is_empty() {
            let dirs: Vec<String> = t.include_dirs.iter().map(|p| inc_path(p)).collect();
            let _ = writeln!(
                s,
                "target_include_directories({} PRIVATE {})",
                t.name,
                dirs.join(" ")
            );
        }

        if t.test {
            if let Some(dir) = opts.testkit_dir {
                let _ = writeln!(
                    s,
                    "target_include_directories({} PRIVATE {})",
                    t.name,
                    quote_always(&to_posix(dir))
                );
            }
        }

        let visibility = if t.kind.is_library() {
            "PUBLIC"
        } else {
            "PRIVATE"
        };

        if !t.definitions.is_empty() {
            let _ = writeln!(
                s,
                "target_compile_definitions({} {} {})",
                t.name,
                visibility,
                t.definitions.join(" ")
            );
        }
        if !t.compile_options.is_empty() {
            let _ = writeln!(
                s,
                "target_compile_options({} PRIVATE {})",
                t.name,
                t.compile_options.join(" ")
            );
        }

        let mut links: Vec<String> = t.deps.clone();
        links.extend(t.link_libraries.iter().cloned());
        if !links.is_empty() {
            let _ = writeln!(
                s,
                "target_link_libraries({} {} {})",
                t.name,
                visibility,
                links.join(" ")
            );
        }
        if !t.link_options.is_empty() {
            let _ = writeln!(
                s,
                "target_link_options({} PRIVATE {})",
                t.name,
                t.link_options.join(" ")
            );
        }
        if let Some(std) = t.cxx_std {
            let _ = writeln!(
                s,
                "target_compile_features({} PRIVATE cxx_std_{std})",
                t.name
            );
        }
        if let Some(name) = &t.output_name {
            let _ = writeln!(
                s,
                "set_target_properties({} PROPERTIES OUTPUT_NAME {})",
                t.name,
                quote(name)
            );
        }

        emit_post_build(s, t);
    }
}

/// 源文件路径：相对项目根的一律拼上 `${YUBILD_SOURCE_ROOT}`，绝对路径原样保留。
fn src_path(rel: &str) -> String {
    if is_absolute(rel) {
        quote_always(&to_posix(rel))
    } else {
        format!("\"${{YUBILD_SOURCE_ROOT}}/{}\"", to_posix(rel))
    }
}

fn inc_path(rel: &str) -> String {
    src_path(rel)
}

pub fn is_absolute(p: &str) -> bool {
    if p.starts_with('/') || p.starts_with('\\') {
        return true;
    }
    // Windows 盘符：C:/ 或 C:\
    let b = p.as_bytes();
    b.len() >= 3 && b[1] == b':' && (b[2] == b'/' || b[2] == b'\\') && b[0].is_ascii_alphabetic()
}

pub fn to_posix(p: &str) -> String {
    p.replace('\\', "/")
}

fn normalize_root(raw: &str) -> String {
    let p = to_posix(raw);
    let trimmed = p.trim_end_matches('/').to_string();
    if trimmed.is_empty() {
        "/".to_string()
    } else {
        trimmed
    }
}

fn quote(p: &str) -> String {
    if p.is_empty() || p.contains(' ') || p.contains('\t') {
        quote_always(p)
    } else {
        p.to_string()
    }
}

fn quote_always(p: &str) -> String {
    format!("\"{}\"", p.replace('"', "\\\""))
}

/// pkg-config 的变量名：`fmt-core` -> `FMT_CORE`
fn pkg_config_var(pkg: &str) -> String {
    pkg.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect()
}

fn sanitize_ident(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if out.is_empty()
        || out
            .chars()
            .next()
            .map(|c| c.is_ascii_digit())
            .unwrap_or(false)
    {
        out.insert(0, '_');
    }
    out
}

